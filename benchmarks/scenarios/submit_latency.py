"""submit_latency — how long from ``flash.submit(...)`` to the child's FIRST
training step, and where does that time go?

HYPOTHESIS: flash.submit adds a small, roughly CONSTANT wall-clock overhead
before user code reaches its first step — dominated by child-process launch
(python interpreter startup), not by flashruntime's own bookkeeping — and that
constant is invisible next to any real training run measured in minutes.

MEASUREMENT METHOD (auditable from this file alone):
  A tiny stdlib trainer (written by this file — no torch, no faults.py) stamps
  two wall-clock instants into its metrics.json:
    * ``proc_start_ts`` — ``time.time()`` on the child's VERY FIRST line (right
      after importing ``time``), i.e. the earliest observable point inside the
      spawned process, AFTER the OS/python interpreter has finished starting it.
    * ``first_step_ts`` — ``time.time()`` the instant the child reaches its first
      "training step" (after its trivial setup).
  The parent records ``t0 = time.time()`` immediately BEFORE ``flash.submit`` and,
  because both clocks are the same machine wall clock, derives three durations
  per submit from the collected metrics:

      total        = first_step_ts - t0          # submit call → first step (the headline)
      phase_launch = proc_start_ts - t0          # submit call → child process start
                                                 #   (submit machinery + interpreter startup)
      phase_child  = first_step_ts - proc_start_ts  # child's own setup → first step

  ``phase_launch + phase_child == total`` by construction (the two instants
  bracket the same interval), so the split ATTRIBUTES the constant honestly:
  interpreter startup lands in launch (it IS launch cost), user setup in child.

  COLD vs WARM (reported separately, both MEASURED):
    * cold — N submits, each into a FRESH output_dir (mkdtemp per submit): the
      cold-directory path (new inode, no warm page cache). ``median`` = cold p50
      (the headline), ``cold_p95`` its tail.
    * warm — N back-to-back submits into ONE reused output_dir, keeping the
      2nd..Nth (the 1st primes the dir/page cache). ``warm_p50``/``warm_p95``.
    The child is a fresh process EITHER way (its interpreter startup is never
    warmed by the parent), so cold≈warm here — the small delta is the OS
    file-cache effect, MEASURED and shown, never assumed away.

  Honest framing: this is a CONSTANT per-launch overhead. At real-training
  scale (minutes to hours) it is a rounding error; it matters only for very
  short jobs or very wide fan-outs, which is exactly why we report it, split it,
  and never amortize it away.
"""

from __future__ import annotations

import sys
import tempfile
import time
from pathlib import Path

from benchmarks._util import ensure_venv_on_path, median, percentile
from benchmarks.schema import ResultRow

name = "submit_latency"
hypothesis = (
    "flash.submit adds a small, roughly constant overhead before user code hits "
    "its first step — dominated by child-process launch, not flashruntime "
    "bookkeeping — invisible next to any real training run."
)

FULL_N = 20   # the full baseline (cold p50/p95 over 20 fresh-dir submits)
SMOKE_N = 3   # the bench_smoke variant

# A minimal stdlib trainer. It stamps proc_start_ts on its very first line, does
# trivial "setup", stamps first_step_ts, and writes metrics.json to its cwd (the
# collect-glob the SDK copies out) — the whole point is to isolate LAUNCH cost,
# so setup is deliberately near-empty (a real trainer's setup would land, honestly,
# in phase_child). No argparse/heavy imports before the stamps: they would tax
# phase_child and muddy the launch/child attribution.
_TRAINER = '''#!/usr/bin/env python
"""Auto-generated by benchmarks/scenarios/submit_latency.py — a stdlib latency probe.

First line stamps proc_start_ts (earliest observable point in the child); after a
trivial setup it stamps first_step_ts and writes both to metrics.json in cwd, which
flash.submit collects. No torch, no argparse before the stamps — this measures the
launch→first-step overhead, nothing else.
"""
import time
proc_start_ts = time.time()          # VERY FIRST line: the child has started
import json
from pathlib import Path

# trivial setup stands in for a real trainer's model/data init (kept near-empty so
# phase_child reflects overhead, not synthetic work)
_ = sum(range(1000))

first_step_ts = time.time()          # the child reaches its first "training step"
Path("metrics.json").write_text(json.dumps({
    "proc_start_ts": proc_start_ts,
    "first_step_ts": first_step_ts,
}))
'''


def _write_trainer(src: Path) -> Path:
    src.mkdir(parents=True, exist_ok=True)
    path = src / "latency_trainer.py"
    path.write_text(_TRAINER)
    return path


def _one_submit(flash, workload, out: Path) -> tuple[float, float, float]:
    """One submit; returns ``(total, phase_launch, phase_child)`` seconds, all
    derived from the child's stamped instants and the parent's t0. Raises loudly
    if the child did not stamp both instants (a broken probe must fail, never
    silently report a bogus 0)."""
    t0 = time.time()
    run = flash.submit(workload, output_dir=out)
    if run.state.value != "SUCCEEDED" or not run.trials:
        raise RuntimeError(f"submit_latency child failed:\n{run.logs()}")
    m = run.trials[0]
    proc_start_ts = m["proc_start_ts"]
    first_step_ts = m["first_step_ts"]
    total = first_step_ts - t0
    phase_launch = proc_start_ts - t0
    phase_child = first_step_ts - proc_start_ts
    return total, phase_launch, phase_child


def _latency(n: int) -> ResultRow:
    """Measure submit→first-step latency over ``n`` cold submits (fresh output_dir
    each) plus a warm pass (``n`` back-to-back submits into one reused dir, keeping
    the 2nd..Nth). All numbers MEASURED from the child's stamped instants."""
    ensure_venv_on_path()
    import flashruntime as flash
    from flashruntime.workloads.command import CommandWorkload, OutputSpec, Source

    n = max(1, n)
    with tempfile.TemporaryDirectory(prefix="submit-latency-") as td:
        root = Path(td)
        src = root / "src"
        _write_trainer(src)

        workload = CommandWorkload(
            command=[sys.executable, "latency_trainer.py"],
            source=Source(path=str(src)),
            outputs=OutputSpec(collect=["metrics.json"]),
        )

        # cold pass — a FRESH output_dir per submit (new dir, cold page cache).
        cold_total: list[float] = []
        cold_launch: list[float] = []
        cold_child: list[float] = []
        for i in range(n):
            total, launch, child = _one_submit(flash, workload, root / f"cold-{i:03d}")
            cold_total.append(total)
            cold_launch.append(launch)
            cold_child.append(child)

        # warm pass — n submits into ONE reused output_dir; drop the priming 1st,
        # keep the 2nd..Nth (interpreter/page cache hot). With n==1 there is no
        # warm sample, so fall back to the single warm submit's number.
        warm_dir = root / "warm"
        warm_total: list[float] = []
        for i in range(n):
            total, _launch, _child = _one_submit(flash, workload, warm_dir)
            if i >= 1 or n == 1:
                warm_total.append(total)

    cold_p50 = median(cold_total)
    comparators = {
        "cold_p95": round(percentile(cold_total, 0.95), 4),
        "warm_p50": round(median(warm_total), 4),
        "warm_p95": round(percentile(warm_total, 0.95), 4),
        # medians of the per-submit phase split (launch dominates: it carries the
        # child's interpreter startup, which is the bulk of the constant overhead).
        "phase_launch_s": round(median(cold_launch), 4),
        "phase_child_s": round(median(cold_child), 4),
    }
    notes = [
        "total = child.first_step_ts − parent.t0 (submit call → first training step), MEASURED "
        "from wall-clock instants the child stamps into metrics.json — never a baked figure",
        "phase_launch_s (submit call → child proc start) + phase_child_s (proc start → first "
        "step) == total by construction; interpreter startup lands in launch (it IS launch cost)",
        "cold = fresh output_dir per submit (cold dir/page cache); warm = 2nd..Nth of a reused "
        "dir (hot cache). The child is a fresh process either way, so cold≈warm — the small "
        "delta is the OS file-cache effect, MEASURED, not assumed away",
        "this is a CONSTANT per-launch overhead: invisible at real-training scale (minutes+); "
        "it matters only for very short jobs or very wide fan-outs — which is why we split and "
        "report it rather than amortize it away",
    ]
    return ResultRow(
        scenario=name,
        unit="s (p50 cold)",
        median=round(cold_p50, 4),
        p10=round(percentile(cold_total, 0.1), 4),
        p90=round(percentile(cold_total, 0.9), 4),
        repeats=n,
        comparators=comparators,
        notes=notes,
    )


def run(repeats: int) -> ResultRow:
    """The full baseline. ``repeats`` is the cold-sample count N (CLI ``--repeats``);
    the brief's full run is ``--repeats 20`` (== FULL_N), floored at 3 so the row
    always renders (report.py refuses repeats < 3 outside --smoke)."""
    return _latency(max(3, repeats))
