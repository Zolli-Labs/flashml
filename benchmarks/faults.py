"""Fault-injection helpers shared by the resilience scenarios.

Three primitives, each with a single job, so a scenario file stays a thin
description of WHAT to inject and leaves the mechanics here (the T2/T3
scenarios consume these signatures verbatim — do not drift them):

  * ``write_crashy_trainer`` — materialise a self-contained *stdlib-only*
    training script (no torch, so the matrix runs on any box) that checkpoints
    under the manifest contract and can crash itself in one of three ways.
  * ``kill_child`` — externally SIGKILL a ``wait=False`` run's newest attempt
    the instant a caller-supplied predicate first fires (node-loss / hang /
    mid-write faults the script cannot inject on itself).
  * ``corrupt_newest_part`` — flip bytes inside the newest valid checkpoint's
    largest part, so it fails hash verification and recovery must fall back to
    an earlier manifest (the corrupt-checkpoint fault).

Pure stdlib + ``flashruntime.checkpoint.local`` (itself pydantic-only) — importing
this module never pulls torch/numpy in.
"""

from __future__ import annotations

import os
import signal
import time
from pathlib import Path
from typing import Callable

from flashruntime.checkpoint.local import latest_valid_manifest

# The generated script embeds two injection points (crash import + crash mode)
# and two baked defaults (steps + checkpoint-every, still CLI-overridable). Kept
# as a plain template with ``__MARKER__`` replacements, not an f-string, so the
# script's own ``{step:06d}`` / ``.format`` literals need no brace-escaping.
_TEMPLATE = '''#!/usr/bin/env python
"""Auto-generated by benchmarks/faults.py — a stdlib-only crash simulator.

It exercises flashruntime's checkpoint MANIFEST contract directly (parts written
first, manifest.json written last) instead of torch, so the fault-recovery
matrix needs no GPU/torch to prove the resume path.
"""
import argparse
import json
import os
import time
from pathlib import Path
__CRASH_IMPORT__
from flashruntime.checkpoint.local import latest_valid_manifest, write_manifest

CRASH = "__CRASH_MODE__"
# ~8 MB of "weights": writing plus sha256-hashing a part this size takes a few
# ms, which WIDENS the (part-on-disk, manifest-absent) write window so an
# external SIGKILL can reliably land inside it (fault-matrix case d). Smaller
# and the window closes faster than a poller can observe it.
TENSOR_BYTES = 8 * 1024 * 1024
# A stdlib loop with no compute would finish before any external watcher sees
# intermediate state; this per-step pause keeps a run observable long enough for
# kill_child to catch the manifest / write-window it is waiting on.
STEP_SLEEP_S = 0.004


def _ckpt_root() -> Path:
    root = os.environ.get("FLASHML_CKPT_DIR")
    return Path(root) if root else Path(os.environ.get("FLASHML_OUTPUT_DIR", ".")) / "ckpt"


def _save(root: Path, step: int, payload: bytes) -> None:
    step_dir = root / f"step-{step:06d}"
    step_dir.mkdir(parents=True, exist_ok=True)
    (step_dir / "model.pt").write_bytes(payload)   # the part — written FIRST
    write_manifest(                                 # manifest — written LAST
        step_dir,
        job_id=os.environ.get("FLASHML_JOB_ID", "local"),
        attempt_id=os.environ.get("FLASHML_ATTEMPT_ID", "local"),
        step=step,
        framework="stdlib-fault-sim",
    )


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--steps", type=int, default=__STEPS__)
    ap.add_argument("--checkpoint-every", type=int, default=__EVERY__)
    args = ap.parse_args()

    root = _ckpt_root()
    manifest = latest_valid_manifest(root)
    start = manifest.step if manifest is not None else 0   # >0 ⇒ this is a resume
    trigger = max(1, args.steps // 2)                      # midpoint crash/hang point
    payload = b"\\x5a" * TENSOR_BYTES

    step = start
    while step < args.steps:
        step += 1
        if args.checkpoint_every > 0 and step % args.checkpoint_every == 0:
            _save(root, step, payload)
        time.sleep(STEP_SLEEP_S)
        # Fault markers fire FRESH-RUN-ONLY (start == 0): a resumed retry sails
        # past them and finishes. The key is checkpoint progress, not wall-clock.
        if start == 0 and step >= trigger:
            if CRASH == "systemexit_mid":
                raise SystemExit(3)          # bare int ⇒ no traceback ⇒ WORKER_CRASH
            if CRASH == "hang_after_step":
                while True:
                    time.sleep(3600)         # wait to be SIGKILLed from outside

    _save(root, step, payload)               # final checkpoint
    result = {"steps": step, "resumed_from": start}
    Path("metrics.json").write_text(json.dumps(result))
    print(json.dumps(result))


if __name__ == "__main__":
    main()
'''


def write_crashy_trainer(
    dir: Path, *, steps: int, checkpoint_every: int, crash: str | None
) -> Path:
    """Write a self-contained stdlib+flashruntime training script into ``dir``.

    ``crash`` selects the injected fault (T2/T3 pass one of these verbatim):
      * ``None`` — a clean run that checkpoints every ``checkpoint_every`` steps
        and finishes (the substrate the external-kill / corruption cases drive).
      * ``"import_error"`` — a top-level ``import definitely_not_a_module`` that
        dies at import (a deterministic APPLICATION_ERROR → fail-fast).
      * ``"systemexit_mid"`` — ``raise SystemExit(3)`` at the midpoint on a fresh
        run only; a resumed retry passes it (WORKER_CRASH → auto-resume).
      * ``"hang_after_step"`` — sleeps forever past the midpoint on a fresh run,
        so an external watcher can SIGKILL it once a checkpoint exists.

    ``steps`` / ``checkpoint_every`` are baked as the script's argparse defaults
    (still overridable on the command line). Returns the script path.
    """
    dir = Path(dir)
    dir.mkdir(parents=True, exist_ok=True)
    crash_import = "import definitely_not_a_module" if crash == "import_error" else ""
    text = (
        _TEMPLATE.replace("__CRASH_IMPORT__", crash_import)
        .replace("__CRASH_MODE__", str(crash))
        .replace("__STEPS__", str(int(steps)))
        .replace("__EVERY__", str(int(checkpoint_every)))
    )
    path = dir / f"crashy_trainer_{crash or 'clean'}.py"
    path.write_text(text)
    return path


def _newest_pid(run) -> int | None:
    """The pid of the newest attempt carrying one. ``Run.attempts`` rows store
    ``pid`` as a string (the launcher's execution_id); the newest row is the
    live process for a single-launch fault."""
    for row in reversed(list(run.attempts)):
        pid = row.get("pid")
        if pid:
            try:
                return int(pid)
            except (TypeError, ValueError):
                continue
    return None


def kill_child(
    run,
    *,
    sig: int = signal.SIGKILL,
    when: Callable[[], bool],
    timeout_s: float,
) -> bool:
    """Signal a ``wait=False`` run's newest attempt the first time ``when()``
    fires, and report whether it fired.

    Polls ``run.attempts`` for the live pid (only the polling seam is used, so a
    stub exposing ``.attempts`` drives it in tests). Returns True once a signal
    is delivered to a live process; False if ``timeout_s`` elapses without
    ``when()`` ever becoming true (or the target was already gone every time).
    """
    deadline = time.monotonic() + timeout_s
    while time.monotonic() < deadline:
        if when():
            pid = _newest_pid(run)
            if pid is not None:
                try:
                    os.kill(pid, sig)
                    return True
                except ProcessLookupError:
                    pass  # target already exited; keep watching for a live one
        time.sleep(0.001)
    return False


def corrupt_newest_part(ckpt_root: Path) -> Path | None:
    """Flip a run of bytes mid-file in the newest VALID manifest's largest part.

    After this the manifest fails ``verify_manifest`` (hash mismatch), so
    ``latest_valid_manifest`` skips it and recovery restores from an earlier
    manifest. Returns the corrupted part path, or None when there is no valid
    manifest / part to hit.
    """
    ckpt_root = Path(ckpt_root)
    manifest = latest_valid_manifest(ckpt_root)
    if manifest is None or not manifest.parts:
        return None
    step_dir = Path(manifest.storage_prefix)
    largest = max(manifest.parts, key=lambda p: p.size_bytes)
    target = step_dir / largest.key
    data = bytearray(target.read_bytes())
    if not data:
        return None
    mid = len(data) // 2
    for i in range(mid, min(mid + 64, len(data))):  # a contiguous mid-file smear
        data[i] ^= 0xFF
    target.write_bytes(data)
    return target
